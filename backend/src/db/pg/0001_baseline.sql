-- Enabling a subscription starts its comment scan from that moment (the SQLite triggers
-- comment_scan_enable_insert / comment_scan_enable_update).
CREATE FUNCTION comment_scan_enable() RETURNS trigger
  LANGUAGE plpgsql
  AS $$
BEGIN
  INSERT INTO comment_scan_cursors (repo_id, enabled_at, checkpoint)
  VALUES (NEW.repo_id, NEW.updated_at, NEW.updated_at)
  ON CONFLICT (repo_id) DO UPDATE SET enabled_at = excluded.enabled_at, checkpoint = excluded.checkpoint;
  RETURN NULL;
END
$$;

CREATE TRIGGER comment_scan_enable_insert AFTER INSERT ON subscriptions
  FOR EACH ROW WHEN (NEW.enabled = 1) EXECUTE FUNCTION comment_scan_enable();

CREATE TRIGGER comment_scan_enable_update AFTER UPDATE OF enabled ON subscriptions
  FOR EACH ROW WHEN (NEW.enabled = 1 AND OLD.enabled = 0) EXECUTE FUNCTION comment_scan_enable();

