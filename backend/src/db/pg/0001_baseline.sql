-- Postgres baseline: the SQLite schema at user_version 3 (schema.sql, gemini_accounts.sql,
-- more_providers.sql), translated. Every TEXT column uses the "C" collation so ordering and
-- comparisons stay byte-wise, as they were in SQLite; cache keys hash ordered path lists.
-- Repos are never hard-deleted (`removed_at`), and their history references RESTRICT so a stray
-- delete fails instead of cascading through reviews already published on GitHub.

-- JSON lives in TEXT exactly as written (hashes and comparisons read the stored bytes). Queries
-- that look inside it go through try_jsonb, which yields NULL for invalid JSON the way the SQLite
-- `CASE WHEN json_valid(x) THEN json_extract(...) END` guards did.
CREATE FUNCTION try_jsonb(value TEXT) RETURNS JSONB
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
  AS $$ SELECT CASE WHEN pg_input_is_valid(value, 'jsonb') THEN value::jsonb END $$;

