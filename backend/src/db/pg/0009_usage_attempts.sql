-- One row per model per account execution of a review stage, written when the execution ends
-- (success, account failover, failure or cancellation). A stage that fails over or repairs its
-- output runs more than once, possibly on different accounts; this is what attributes those
-- tokens to the account and model that spent them. The account is a snapshot, not a foreign key,
-- so usage stays attributed after the account is removed.
CREATE TABLE review_run_usage_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id BIGINT NOT NULL REFERENCES review_runs(id) ON DELETE CASCADE,
  pr_id BIGINT NOT NULL,
  stage TEXT COLLATE "C" NOT NULL,
  account_id BIGINT,
  account_label TEXT COLLATE "C",
  provider TEXT COLLATE "C",
  model TEXT COLLATE "C" NOT NULL,
  input_tokens BIGINT NOT NULL DEFAULT 0,
  output_tokens BIGINT NOT NULL DEFAULT 0,
  cache_read_tokens BIGINT NOT NULL DEFAULT 0,
  cache_creation_tokens BIGINT NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL
);

CREATE INDEX idx_review_run_usage_attempts_run ON review_run_usage_attempts(run_id);

-- The Usage page reads runs by creation time across PRs (within one PR, idx_review_runs_pr_created).
CREATE INDEX idx_review_runs_created ON review_runs(created_at);
